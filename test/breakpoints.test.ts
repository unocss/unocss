const containerExpansion = 'max-w-full sm:max-w-540px md:max-w-720px lg:max-w-960px xl:max-w-1140px'
const containerWidths = ['100%', '540px', '720px', '960px', '1140px']

function maxWidths(css: string) {
  const declarations: { value: string, queries: string[] }[] = []
  postcss.parse(css).walkDecls('max-width', (decl) => {
    const queries: string[] = []
    let parent: postcss.AnyNode | undefined = decl.parent
    while (parent) {
      if (parent.type === 'atrule') {
        expect(parent.name).toBe('media')
        queries.unshift(parent.params)
      }
      parent = parent.parent
    }
    declarations.push({ value: decl.value, queries })
  })
  return declarations
}

// Only the min/max-width conjunctions generated by these breakpoint fixtures.
function widthAt(declarations: ReturnType<typeof maxWidths>, viewport: number) {
  return declarations.filter(({ queries }) => queries.every((query) => {
    const normalized = query.replace(/calc\(([\d.]+)(rem|px) - 0.1px\)/g, (_, n, unit) => `${Number(n) * (unit === 'rem' ? 16 : 1) - 0.1}px`)
    return normalized.split(' and ').every((condition) => {
      const match = condition.match(/^\((min|max)-width: ([\d.]+)(px|rem)\)$/)!
      expect(match).not.toBeNull()
      const bound = Number(match[2]) * (match[3] === 'rem' ? 16 : 1)
      return match[1] === 'min' ? viewport >= bound : viewport <= bound
    })
  })).at(-1)?.value
}

describe.each([
  { name: 'mini', preset: presetMini, theme: {}, points: ['640px', '768px', '1024px', '1280px'] },
  { name: 'wind3', preset: presetWind3, theme: {}, points: ['640px', '768px', '1024px', '1280px'] },
  { name: 'wind4 pixels', preset: presetWind4, theme: { breakpoint: { 'sm': '640px', 'md': '768px', 'lg': '1024px', 'xl': '1280px', '2xl': '1536px' } }, points: ['640px', '768px', '1024px', '1280px'] },
  { name: 'wind4 rems', preset: presetWind4, theme: {}, points: ['40rem', '48rem', '64rem', '80rem'] },
])('$name composed breakpoint ordering', ({ preset, theme, points }) => {
  it.each(['', 'sm:', 'md:', 'xl:', 'sm:nested-'])('preserves shortcut progression: %s', async (prefix) => {
    const uno = await createGenerator<object>({
      presets: [preset()],
      theme,
      shortcuts: [
        ['custom-container', containerExpansion, { layer: 'default' }],
        ['nested-custom-container', 'custom-container', { layer: 'default' }],
      ],
    })
    const token = `${prefix}custom-container`
    const { css, matched } = await uno.generate(token, { preflights: false })
    expect([...matched]).toEqual([token])
    const declarations = maxWidths(css)
    expect(declarations.map(d => d.value)).toEqual(containerWidths)
    const outer = prefix.startsWith('md:') ? 1 : prefix.startsWith('xl:') ? 3 : 0
    expect(declarations.map(d => d.queries)).toEqual([
      ...(prefix ? [[`(min-width: ${points[outer]})`]] : [[]]),
      ...points.map(point => [`(min-width: ${point})`, ...(prefix ? [`(min-width: ${points[outer]})`] : [])]),
    ])
    const activation = prefix ? [640, 768, 1024, 1280][outer] : 0
    expect([639, 640, 767, 768, 1023, 1024, 1279, 1280].map(viewport => widthAt(declarations, viewport)))
      .toEqual([639, 640, 767, 768, 1023, 1024, 1279, 1280].map(viewport => viewport < activation ? undefined : viewport < 640 ? '100%' : viewport < 768 ? '540px' : viewport < 1024 ? '720px' : viewport < 1280 ? '960px' : '1140px'))
  })

  it.each(['', 'sm:'])('preserves direct responsive utility progression: %s', async (prefix) => {
    const uno = await createGenerator<object>({ presets: [preset()], theme })
    const tokens = containerExpansion.split(' ').map(token => `${prefix}${token}`)
    const { css, matched } = await uno.generate(tokens, { preflights: false })
    expect([...matched].sort()).toEqual(tokens.toSorted())
    expect(maxWidths(css).map(d => d.value)).toEqual(containerWidths)
  })

  it.each(['default', 'shortcuts'])('keeps ordering alongside an unranked shortcut in the %s layer', async (layer) => {
    const create = () => createGenerator<object>({
      presets: [preset()],
      theme,
      shortcuts: [
        ['custom-container', containerExpansion, { layer: 'default' }],
        ['other', `min-[${points[3]}]:text-red`, { layer }],
      ],
    })
    const tokens = ['sm:custom-container', 'sm:other']
    const check = async (warmup: string[], reversed: boolean) => {
      const uno = await create()
      for (const token of warmup)
        await uno.generate(token, { preflights: false })
      const { css, matched } = await uno.generate(reversed ? tokens.toReversed() : tokens, { preflights: false })
      expect([...matched].sort()).toEqual(tokens.toSorted())
      const declarations = maxWidths(css)
      expect(declarations.map(d => d.value)).toEqual(containerWidths)
      expect(widthAt(declarations, 1280)).toBe('1140px')
      return css
    }
    const css = await check([], false)
    expect(await check([], true)).toBe(css)
    expect(await check(tokens, true)).toBe(css)
    expect(await check(tokens.toReversed(), false)).toBe(css)
  })

  it.each([
    { token: 'md:probe', expansion: 'max-w-full sm:max-w-540px xl:max-w-1140px', widths: [undefined, '540px', '540px', '1140px'] },
    { token: 'sm:probe', expansion: 'max-w-full sm:md:max-w-720px xl:max-w-1140px', widths: ['100%', '720px', '720px', '1140px'] },
    { token: 'sm:probe', expansion: 'max-w-full lt-xl:max-w-540px lt-md:max-w-320px', widths: ['320px', '540px', '540px', '100%'] },
    { token: 'sm:probe', expansion: 'max-w-full at-sm:max-w-540px at-md:max-w-720px', widths: ['540px', '720px', '100%', '100%'] },
  ])('retains composed conditions: $expansion', async ({ token, expansion, widths }) => {
    const uno = await createGenerator<object>({ presets: [preset()], theme, shortcuts: [['probe', expansion, { layer: 'default' }]] })
    const { css, matched } = await uno.generate(token, { preflights: false })
    expect([...matched]).toEqual([token])
    const declarations = maxWidths(css)
    expect(declarations).toHaveLength(3)
    expect([640, 768, 1024, 1280].map(viewport => widthAt(declarations, viewport))).toEqual(widths)
    if (expansion.includes('lt-') || expansion.includes('at-')) {
      const upperBounds = points[0].endsWith('rem')
        ? ['calc(48rem - 0.1px)', `calc(${points[expansion.includes('lt-') ? 3 : 2]} - 0.1px)`]
        : ['767.9px', expansion.includes('lt-') ? '1279.9px' : '1023.9px']
      for (const bound of upperBounds)
        expect(css).toContain(`max-width: ${bound}`)
    }
  })
})

it('orders composed custom rem breakpoints by priority rather than query text', async () => {
  const uno = await createGenerator({
    presets: [presetWind4()],
    theme: { breakpoint: { sm: '40rem', md: '48rem', lg: '64rem', xl: '100rem' } },
    shortcuts: [['custom-container', containerExpansion, { layer: 'default' }]],
  })
  const { css } = await uno.generate('sm:custom-container', { preflights: false })
  const declarations = maxWidths(css)
  expect(declarations.map(d => d.value)).toEqual(containerWidths)
  expect(widthAt(declarations, 1600)).toBe('1140px')
})
